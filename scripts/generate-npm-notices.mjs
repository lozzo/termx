#!/usr/bin/env node

import { createHash } from 'node:crypto'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.slice(2).includes('--check')
if (process.argv.length > (check ? 3 : 2)) {
  throw new Error('usage: generate-npm-notices.mjs [--check]')
}

const approvedLicenses = new Set([
  '0BSD',
  'Apache-2.0',
  'BlueOak-1.0.0',
  'BSD-3-Clause',
  'ISC',
  'MIT',
  'Unlicense',
  '(Apache-2.0 AND BSD-3-Clause)',
])

const lockPath = join(repoRoot, 'package-lock.json')

const overrides = new Map([
  [
    'bplist-parser@0.3.2',
    [join(repoRoot, 'docs/legal/third-party/npm/bplist-parser-0.3.2-LICENSE.txt')],
  ],
  [
    '@bufbuild/protobuf@2.12.0',
    [
      join(repoRoot, 'docs/legal/third-party/npm/bufbuild-protobuf-2.12.0-Apache-2.0.txt'),
      join(repoRoot, 'docs/legal/third-party/npm/bufbuild-protobuf-2.12.0-BSD-3-Clause.txt'),
    ],
  ],
])

function packageName(packagePath) {
  const marker = 'node_modules/'
  const suffix = packagePath.slice(packagePath.lastIndexOf(marker) + marker.length)
  const parts = suffix.split('/')
  return parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]
}

function normalizeText(path) {
  return readFileSync(path, 'utf8')
    .replace(/\r\n/g, '\n')
    .replace(/[ \t]+$/gm, '')
    .replace(/\s*$/, '\n')
}

function licenseFiles(packageRoot) {
  return readdirSync(packageRoot)
    .filter((name) => /^(licen[cs]e|copying|notice)([-.].*)?$/i.test(name))
    .sort()
    .map((name) => join(packageRoot, name))
}

const dependencies = new Map()
const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
if (lock.lockfileVersion !== 3 || typeof lock.packages !== 'object') {
  throw new Error(`${relative(repoRoot, lockPath)} must be a package-lock v3 file`)
}
for (const [packagePath, metadata] of Object.entries(lock.packages)) {
  if (!packagePath.includes('node_modules/') || metadata.dev) {
    continue
  }
  const name = packageName(packagePath)
  if (name.startsWith('@termx/')) {
    continue
  }
  if (!metadata.version || !metadata.license) {
    throw new Error(`${packagePath} is missing version or license metadata`)
  }
  if (!approvedLicenses.has(metadata.license)) {
    throw new Error(`${name}@${metadata.version} has unapproved license ${metadata.license}`)
  }
  const id = `${name}@${metadata.version}`
  const packageRoot = join(repoRoot, packagePath)
  if (!existsSync(packageRoot)) {
    throw new Error(`${packagePath} is not installed; run npm ci from the repository root before the license audit`)
  }
  let files = licenseFiles(packageRoot)
  if (files.length === 0) {
    files = overrides.get(id) ?? []
  }
  if (files.length === 0 || files.some((path) => !existsSync(path))) {
    throw new Error(`${id} has no distributable license text`)
  }
  const current = dependencies.get(id)
  if (current && current.license !== metadata.license) {
    throw new Error(`${id} has inconsistent license metadata`)
  }
  dependencies.set(id, {
    id,
    license: metadata.license,
    files,
  })
}

const documents = new Map()
for (const dependency of [...dependencies.values()].sort((a, b) => a.id.localeCompare(b.id))) {
  dependency.documentIDs = []
  for (const path of dependency.files) {
    const text = normalizeText(path)
    const hash = createHash('sha256').update(text).digest('hex')
    const documentID = `sha256:${hash}`
    dependency.documentIDs.push(documentID)
    const document = documents.get(documentID) ?? {
      id: documentID,
      text,
      sources: new Set(),
      dependencies: new Set(),
    }
    document.sources.add(relative(repoRoot, path))
    document.dependencies.add(dependency.id)
    documents.set(documentID, document)
  }
  dependency.documentIDs.sort()
}

const licenseCounts = new Map()
for (const dependency of dependencies.values()) {
  licenseCounts.set(dependency.license, (licenseCounts.get(dependency.license) ?? 0) + 1)
}

const lines = [
  'TermX App npm Third-Party Notices',
  '',
  'Generated by scripts/generate-npm-notices.mjs from production entries in',
  'the root package-lock.json npm workspace. Development-only',
  'packages and first-party @termx packages are excluded.',
  '',
  'LICENSE SUMMARY',
]
for (const [license, count] of [...licenseCounts.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`${license}: ${count}`)
}
lines.push('', 'DEPENDENCIES')
for (const dependency of [...dependencies.values()].sort((a, b) => a.id.localeCompare(b.id))) {
  lines.push(`${dependency.id} | ${dependency.license} | ${dependency.documentIDs.join(', ')}`)
}
lines.push('', 'LICENSE DOCUMENTS')
for (const document of [...documents.values()].sort((a, b) => a.id.localeCompare(b.id))) {
  lines.push('', '='.repeat(78))
  lines.push(document.id)
  lines.push(`Packages: ${[...document.dependencies].sort().join(', ')}`)
  lines.push(`Sources: ${[...document.sources].sort().join(', ')}`)
  lines.push('='.repeat(78), '', document.text.replace(/\n$/, ''))
}
lines.push('')

const output = `${lines.join('\n').replace(/\n+$/, '')}\n`
const target = join(repoRoot, 'clients/mobile/public/third-party/NPM_NOTICES.txt')
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    throw new Error('clients/mobile/public/third-party/NPM_NOTICES.txt is stale or missing')
  }
} else {
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, output)
}

console.log(`npm notices are ${check ? 'current' : 'updated'} (${dependencies.size} packages, ${documents.size} unique texts)`)
