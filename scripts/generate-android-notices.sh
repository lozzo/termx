#!/usr/bin/env bash

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mode="update"
if [[ "${1:-}" == "--check" ]]; then
  mode="check"
elif [[ $# -ne 0 ]]; then
  echo "usage: $0 [--check]" >&2
  exit 2
fi

tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/muxvia-android-notices.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT

(
  cd "$repo_root/clients/mobile/android"
  ./gradlew -q \
    -I "$repo_root/scripts/android-resolved-dependencies.init.gradle" \
    :app:muxviaResolvedRuntimeDependencies
) | sed -n 's/^MUXVIA_DEPENDENCY //p' | LC_ALL=C sort -u >"$tmp_dir/dependencies.txt"

if [[ ! -s "$tmp_dir/dependencies.txt" ]]; then
  echo "Gradle returned no release runtime dependencies" >&2
  exit 1
fi

classify() {
  local coordinate="$1"
  local group="${coordinate%%:*}"
  case "$coordinate" in
    io.github.webrtc-sdk:android:125.6422.07)
      printf '%s' "Pinned WebRTC composite"
      ;;
    org.java-websocket:Java-WebSocket:1.5.6)
      printf '%s' "MIT"
      ;;
    org.slf4j:slf4j-api:2.0.6)
      printf '%s' "MIT"
      ;;
    org.bouncycastle:bcprov-jdk18on:1.79)
      printf '%s' "MIT"
      ;;
    com.google.protobuf:protobuf-java:3.25.5)
      printf '%s' "Apache-2.0"
      ;;
    androidx.*|org.jetbrains.kotlin:*|org.jetbrains.kotlinx:*|org.jetbrains:annotations:*|org.apache.cordova:*|com.google.code.gson:*|com.google.guava:*|org.jspecify:*)
      printf '%s' "Apache-2.0"
      ;;
    *)
      echo "unreviewed Android release dependency: $coordinate" >&2
      exit 1
      ;;
  esac
}

output="$tmp_dir/ANDROID_NOTICES.txt"
{
  printf '%s\n\n' "Muxvia App Android Third-Party Notices"
  printf '%s\n' "Generated by scripts/generate-android-notices.sh from Gradle"
  printf '%s\n\n' "releaseRuntimeClasspath. Capacitor project modules are covered by NPM_NOTICES.txt."
  printf '%s\n' "RESOLVED MAVEN DEPENDENCIES"
  while IFS= read -r coordinate; do
    printf '%s | %s\n' "$coordinate" "$(classify "$coordinate")"
  done <"$tmp_dir/dependencies.txt"
  printf '\n%s\n\n' "WEBRTC"
  printf '%s\n' "io.github.webrtc-sdk:android:125.6422.07 is pinned to repository commit"
  printf '%s\n' "878c5b093f8bbbd4955d1037316484aabe962d18. Its wrapper MIT license is in"
  printf '%s\n\n' "WEBRTC_SDK_WRAPPER_LICENSE.txt; native WebRTC and bundled third-party notices are in WEBRTC.txt."
  printf '%s\n\n' "JAVA-WEBSOCKET MIT LICENSE"
  cat "$repo_root/docs/legal/third-party/android/Java-WebSocket-1.5.6-LICENSE.txt"
  printf '\n%s\n\n' "SLF4J MIT LICENSE"
  cat "$repo_root/docs/legal/third-party/android/slf4j-api-2.0.6-LICENSE.txt"
  printf '\n%s\n\n' "BOUNCY CASTLE MIT LICENSE"
  cat "$repo_root/docs/legal/third-party/android/bcprov-jdk18on-1.79-LICENSE.txt"
  printf '\n%s\n\n' "APACHE LICENSE 2.0"
  cat "$repo_root/LICENSE"
} >"$output"

target="$repo_root/clients/mobile/public/third-party/ANDROID_NOTICES.txt"
if [[ "$mode" == "check" ]]; then
  if [[ ! -f "$target" ]] || ! cmp -s "$output" "$target"; then
    echo "stale or missing Android notices: ${target#$repo_root/}" >&2
    exit 1
  fi
else
  mkdir -p "$(dirname "$target")"
  install -m 0644 "$output" "$target"
fi

echo "Android notices are $mode"
